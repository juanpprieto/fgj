/** The installed pi package root, found through the `pi` on PATH. */
function piPackage(): string | undefined {
	const bin = Bun.which("pi");
	if (!bin) return undefined;
	let dir = realpathSync(bin);
	for (let i = 0; i < 8; i++) {
		dir = dirname(dir);
		const pkg = join(dir, "node_modules", "@earendil-works", "pi-coding-agent");
		if (existsSync(join(pkg, "package.json"))) return pkg;
		if (
			existsSync(join(dir, "package.json")) &&
			dir.endsWith("pi-coding-agent")
		) {
			return dir;
		}
	}
	return undefined;
}

