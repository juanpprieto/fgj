/** Examples that Codex checks when it loads the file: each must match its rule. */
function examplesFor(rule: RuleSpec): string[][] {
	const risk = rule.prefix[1];
	const fromManifest = MANIFEST.filter((v) => v.risk === risk).flatMap((v) =>
		v.examples.map((e) => e.split(" ")),
	);
	return fromManifest.length > 0 ? fromManifest : [[...rule.prefix]];
}

/** Examples that must not match: the same verb under another risk class. */
function counterExamplesFor(rule: RuleSpec): string[][] {
	const other: Record<string, string> = {
		read: "write",
		write: "read",
		destroy: "write",
	};
	const swapped = other[rule.prefix[1] ?? ""];
	return swapped ? [["fgj", swapped, "comment", "list", "1"]] : [];
}

/**
 * Builds `~/.codex/rules/fgj.rules`. Codex loads every `*.rules` file, and it
 * checks each `match` and `not_match` example when it loads the file.
 *
 * @returns The file content.
 * @example
 * await Bun.write(`${codexHome}/rules/fgj.rules`, codexRules());
 */
export function codexRules(): string {
	const blocks = RULES.map((rule) => {
		const lines = [
			"prefix_rule(",
			`    pattern = ${JSON.stringify(rule.prefix)},`,
			`    decision = "${rule.codex}",`,
			`    justification = ${JSON.stringify(rule.why)},`,
			`    match = [${examplesFor(rule)
				.map((e) => JSON.stringify(e))
				.join(", ")}],`,
		];
		const counter = counterExamplesFor(rule);
		if (counter.length > 0) {
			lines.push(
				`    not_match = [${counter.map((e) => JSON.stringify(e)).join(", ")}],`,
			);
		}
		lines.push(")");
		return lines.join("\n");
	});
	return [
		"# Generated by fgj. Do not edit: run `fgj rules install codex` to update.",
		"# The risk class is always the second word, so one prefix rule covers each class.",
		"",
		blocks.join("\n\n"),
		"",
	].join("\n");
}

/**
 * Lists the fgj entries for Claude Code, by permission list.
 *
 * @returns The `allow` and `ask` entries, for example `Bash(fgj read *)`.
 * @example
 * claudeEntries().ask; // ["Bash(fgj destroy *)"]
 */
export function claudeEntries(): { allow: string[]; ask: string[] } {
	const entry = (rule: RuleSpec) =>
		// Always a trailing " *": it also matches the bare command, and it lets
		// harmless extra words such as --json through, as Codex prefix rules do.
		`Bash(${rule.prefix.join(" ")} *)`;
	return {
		allow: RULES.filter((r) => r.claude === "allow").map(entry),
		ask: RULES.filter((r) => r.claude === "ask").map(entry),
	};
}

const FGJ_ENTRY = /^Bash\(fgj[ :)]/;

/**
 * Merges the fgj entries into a Claude Code settings file. fgj owns only the
 * `Bash(fgj …)` entries in `allow` and `ask`: it removes stale ones, adds the
 * current ones, and keeps every other key, entry, and the file's indentation.
 *
 * @param existing - The current file text, or undefined when there is no file.
 * @returns The new file text. The same input always gives the same output.
 * @example
 * await Bun.write(settingsPath, claudeSettings(await readIfExists(settingsPath)));
 */
export function claudeSettings(existing: string | undefined): string {
	const settings = (existing?.trim() ? JSON.parse(existing) : {}) as Record<
		string,
		unknown
	>;
	const indent = existing?.match(/\n([ \t]+)"/)?.[1] ?? "  ";
	const permissions = (settings.permissions ?? {}) as Record<string, unknown>;
	const entries = claudeEntries();
	for (const list of ["allow", "ask"] as const) {
		const current = Array.isArray(permissions[list])
			? (permissions[list] as unknown[])
			: [];
		const kept = current.filter(
			(e) => !(typeof e === "string" && FGJ_ENTRY.test(e)),
		);
		permissions[list] = [...kept, ...entries[list]];
	}
	settings.permissions = permissions;
	return `${JSON.stringify(settings, null, indent)}\n`;
}

/**
 * Picks the fgj-owned part of a Claude Code settings file, for show, status,
 * and diffs. It never returns other keys, because `env` can hold secrets.
 *
 * @param text - A settings file text, or undefined.
 * @returns The fgj entries that the file holds now, by list.
 * @example
 * claudeFgjPart(await Bun.file(settingsPath).text()); // { allow: [...], ask: [...] }
 */
export function claudeFgjPart(text: string | undefined): {
	allow: string[];
	ask: string[];
} {
	const settings = (text?.trim() ? JSON.parse(text) : {}) as {
		permissions?: Record<string, unknown>;
	};
	const pick = (list: string) => {
		const value = settings.permissions?.[list];
		return Array.isArray(value)
			? value.filter(
					(e): e is string => typeof e === "string" && FGJ_ENTRY.test(e),
				)
			: [];
	};
	return { allow: pick("allow"), ask: pick("ask") };
}

/** What the generated pi adapter needs to know. */
export interface PiAdapterOptions {
	/** The command that runs fgj, for example `["/Users/alice/.local/bin/fgj"]`. */
	fgj: readonly string[];
	/** The folder for one-time approvals, from `approvalDir`. */
	approvals: string;
	/** The profile that this role's lane acts as. The global form has none. */
	profile?: string;
}

/**
 * Builds the fgj pi adapter. It replaces pi's `bash` tool, so exactly one fgj
 * adapter may load in a session: pi refuses to start with two. For each bash
 * call that could reach fgj, it asks `fgj hook pi`, which holds the rules, and
 * shows the approval dialog. It hands a one-time approval to the approved call
 * only, and the role form adds that role's `FGJ_PROFILE` to every call. pi has
 * no allow result, so the adapter only asks or blocks.
 *
 * @param options - The fgj command, the approvals folder, and the role's profile.
 * @returns The extension source.
 * @example
 * await Bun.write(`${agentDir}/extensions/fgj-gate.ts`, piExtension({ fgj: [bin], approvals }));
 */
export function piExtension(options: PiAdapterOptions): string {
	const role = options.profile
		? [
				`// This is the role form: every bash call of this lane acts as the fgj profile ${options.profile}.`,
				"// List it in the lane agent's `extensions:`; never load it with another fgj adapter.",
			]
		: [
				"// This is the global form: it binds no profile. A role lane lists its own role",
				"// form instead, in its agent's `extensions:`.",
			];
	return [
		"// Generated by fgj. Do not edit: run `fgj rules install pi` to update.",
		"// The fgj pi adapter. It owns the bash tool. For a bash call that could reach",
		"// fgj, it asks `fgj hook pi` what to do, shows the approval dialog, and hands",
		"// a one-time approval to the approved call only. It guards against accidents:",
		"// a command that runs a script file is out of reach of any text gate.",
		...role,
		'import type { ExtensionAPI } from "@earendil-works/pi-coding-agent";',
		'import { createBashTool } from "@earendil-works/pi-coding-agent";',
		'import { spawnSync } from "node:child_process";',
		'import { randomUUID } from "node:crypto";',
		'import { mkdirSync, readFileSync, writeFileSync } from "node:fs";',
		'import { homedir } from "node:os";',
		'import { join } from "node:path";',
		"",
		"// pi gives its own bash tool the shellPath and shellCommandPrefix settings;",
		"// this bash tool replaces it, so it reads them too. pi reads a project's",
		"// .pi/settings.json only when the human trusts the project.",
		"function piSetting(file: string, key: string): string | undefined {",
		"\ttry {",
		'\t\tconst value = JSON.parse(readFileSync(file, "utf8"))[key];',
		'\t\treturn typeof value === "string" ? value : undefined;',
		"\t} catch {",
		"\t\treturn undefined;",
		"\t}",
		"}",
		"// A leading ~ names the home folder, as pi reads it.",
		"function expandHome(path: string): string {",
		"\treturn path.replace(/^~(?=\\/|$)/, homedir());",
		"}",
		'const AGENT_SETTINGS = join(expandHome(process.env.PI_CODING_AGENT_DIR || join(homedir(), ".pi", "agent")), "settings.json");',
		'const PROJECT_SETTINGS = join(process.cwd(), ".pi", "settings.json");',
		'const GLOBAL_PREFIX = piSetting(AGENT_SETTINGS, "shellCommandPrefix");',
		'const PROJECT_PREFIX = piSetting(PROJECT_SETTINGS, "shellCommandPrefix");',
		"// The tool starts before pi can say whether it trusts the project, so the",
		"// shell comes from the agent settings only.",
		'const SHELL = piSetting(AGENT_SETTINGS, "shellPath");',
		"const SHELL_PATH = SHELL && expandHome(SHELL);",
		"",
		`const FGJ: string[] = ${JSON.stringify(options.fgj)};`,
		`const PROFILE: string | undefined = ${options.profile === undefined ? "undefined" : JSON.stringify(options.profile)};`,
		`const APPROVALS = ${JSON.stringify(options.approvals)};`,
		`const APPROVAL_TTL_MS = ${APPROVAL_TTL_MS};`,
		"// Only text that can reach fgj needs a decision: the name, the word destroy,",
		"// or a profile change. Every other command runs with no fgj call.",
		"const REACHES_FGJ = /fgj|destroy|FGJ_PROFILE/i;",
		"",
		"interface Decision {",
		'\taction: "pass" | "ask" | "block";',
		"\teffects?: string[];",
		"\treason?: string;",
		"\tapproval?: true;",
		"}",
		"",
		"function decide(command: string): Decision {",
		'\t// Quotes and backslashes can hide the name from a plain match: f\\gj, "f"gj.',
		'\tif (!REACHES_FGJ.test(command.replace(/[\'"\\\\]/g, ""))) return { action: "pass" };',
		'\tconst run = spawnSync(FGJ[0] as string, [...FGJ.slice(1), "hook", "pi"], {',
		"\t\tinput: JSON.stringify(PROFILE ? { command, profile: PROFILE } : { command }),",
		'\t\tencoding: "utf8",',
		"\t\ttimeout: 10_000,",
		"\t});",
		"\ttry {",
		"\t\tif (run.status === 0) return JSON.parse(run.stdout) as Decision;",
		"\t} catch {",
		"\t\t// Fall through: fail closed.",
		"\t}",
		"\treturn {",
		'\t\taction: "block",',
		'\t\treason: "fgj: the gate could not check this command, because fgj hook pi failed. Run `fgj help` to check the installed fgj.",',
		"\t};",
		"}",
		"",
		"export default function (pi: ExtensionAPI) {",
		"\t// Commands that a human approved, each for one run.",
		"\tconst approved: string[] = [];",
		"\t// pi says in each tool_call whether it trusts the project; the spawn after it",
		"\t// uses the answer.",
		"\tlet trusted = false;",
		"\tpi.registerTool(",
		"\t\tcreateBashTool(process.cwd(), {",
		"\t\t\t...(SHELL_PATH ? { shellPath: SHELL_PATH } : {}),",
		"\t\t\tspawnHook: (ctx) => {",
		"\t\t\t\tconst env: NodeJS.ProcessEnv = { ...ctx.env };",
		"\t\t\t\tif (PROFILE) env.FGJ_PROFILE = PROFILE;",
		"\t\t\t\t// The prefix goes before the command and a newline, as pi puts it.",
		"\t\t\t\tconst prefix = (trusted ? PROJECT_PREFIX : undefined) ?? GLOBAL_PREFIX;",
		'\t\t\t\tconst command = prefix ? prefix + "\\n" + ctx.command : ctx.command;',
		"\t\t\t\tconst at = approved.indexOf(ctx.command);",
		"\t\t\t\tif (at >= 0) {",
		"\t\t\t\t\tapproved.splice(at, 1);",
		"\t\t\t\t\tconst token = randomUUID();",
		"\t\t\t\t\tmkdirSync(APPROVALS, { recursive: true, mode: 0o700 });",
		"\t\t\t\t\twriteFileSync(join(APPROVALS, token), JSON.stringify({ expires: Date.now() + APPROVAL_TTL_MS }), { mode: 0o600 });",
		"\t\t\t\t\tenv.FGJ_APPROVAL = token;",
		"\t\t\t\t}",
		"\t\t\t\treturn { ...ctx, command, env };",
		"\t\t\t},",
		"\t\t}),",
		"\t);",
		'\tpi.on("tool_call", async (event, ctx) => {',
		'\t\tif (event.toolName !== "bash") return undefined;',
		"\t\ttrusted = ctx.isProjectTrusted();",
		'\t\tconst command = String((event.input as { command?: unknown }).command ?? "");',
		"\t\tconst decision = decide(command);",
		'\t\tif (decision.action === "pass") return undefined;',
		'\t\tif (decision.action === "block" || !ctx.hasUI) {',
		"\t\t\treturn { block: true, reason: decision.reason };",
		"\t\t}",
		'\t\tconst message = "fgj wants to run:\\n\\n  " + command + "\\n\\n" + (decision.effects ?? []).join(" ") + "\\n\\nAllow it?";',
		'\t\tconst ok = await ctx.ui.confirm("fgj: approve a change", message);',
		'\t\tif (!ok) return { block: true, reason: "Declined by the user." };',
		"\t\t// Only a destroy needs the one-time approval.",
		"\t\tif (decision.approval) approved.push(command);",
		"\t\treturn undefined;",
		"\t});",
		"}",
		"",
	].join("\n");
}
