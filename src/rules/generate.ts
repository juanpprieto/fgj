/** One rule: a command prefix and what each harness does with it. */
interface RuleSpec {
	prefix: readonly string[];
	/** Codex decision. `prompt` asks a human for each call. */
	codex: "allow" | "prompt";
	/** Claude Code list: `allow` runs with no prompt; `ask` prompts. */
	claude: "allow" | "ask";
	why: string;
}

